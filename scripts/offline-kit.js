// Generates the offline kit for astro-lab-playground (BMC-19 / GitHub #16):
//   - site/sw.js            (fully generated service worker: manifest + cache)
//   - site/offline/kit.zip  (STORE-method zip of the whole site/ tree)
//
// Node stdlib ONLY. Deterministic: run twice against unchanged content and both
// outputs are byte-for-byte identical (sorted paths, STORE/no-timestamp zip, and
// a cache name that is a content hash). The whole build is a pure function of the
// existing site content: sw.js is generated in-memory and never read back, so the
// version hash (and therefore the zip) cannot depend on the file it is writing.
//
// Run:  node scripts/offline-kit.js
// Then commit both generated outputs (see the .gitignore kit.zip exception).
//
// This module also exports its helpers (still stdlib-only) so tests/offline-kit.test.js
// can run the exact same walk, rebuild to compare bytes, and read the zip back
// without a third-party library.
"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const SITE_DIR = path.join(__dirname, "..", "site");
const SW_REL = "sw.js";
const ZIP_REL = path.join("offline", "kit.zip");

// ---------- hashing ----------
function sha256Buf(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex");
}
function sha256File(absPath) {
  return sha256Buf(fs.readFileSync(absPath));
}

// ---------- CRC-32 (pure JS, so write and read agree on every Node version) ----------
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1);
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

// ---------- walk ----------
// Every file under siteDir, POSIX-relative to the site root, sorted. The kit zip
// itself is the only thing skipped; sw.js is included once it exists on disk.
function toPosix(p) {
  return p.split(path.sep).join("/");
}
function listSiteFiles(siteDir) {
  const out = [];
  (function walk(rel) {
    const absDir = rel ? path.join(siteDir, rel) : siteDir;
    for (const e of fs.readdirSync(absDir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
      const relChild = rel ? rel + "/" + e.name : e.name;
      if (e.isDirectory()) walk(relChild);
      else if (e.isFile()) out.push(relChild);
    }
  })("");
  return out
    .filter((p) => p !== toPosix(ZIP_REL))
    .sort();
}

// ---------- version ----------
// sha256 over the sorted "path + newline + file sha256" list, EXCLUDING the generated
// sw.js (whose bytes embed this very version). Every other walked file feeds it, so
// any content change rolls the cache name and unchanged content does not.
function kitVersion(siteDir, files) {
  const lines = [];
  for (const rel of files) {
    if (rel === SW_REL) continue;
    lines.push(rel + "\n" + sha256File(path.join(siteDir, rel)) + "\n");
  }
  return sha256Buf(Buffer.from(lines.sort().join(""), "utf8"));
}

// ---------- service worker source ----------
// Classic worker: no imports, no workbox. Manifest paths are root-relative to the
// worker scope (the site root), so the same file works from any origin/depth.
function precacheManifest(files) {
  const set = new Set(files);
  set.add(SW_REL); // always ship the worker itself in its own precache
  return Array.from(set).sort().map((p) => "/" + p);
}
function buildSw(version, precache) {
  const body = precache.map((p) => "    " + JSON.stringify(p)).join(",\n");
  return `/* Generated by scripts/offline-kit.js - DO NOT EDIT BY HAND.
 * Offline kit service worker for astro-lab-playground (classic worker, no imports).
 * Cache-first with network fallback; navigations fall back to the cached page, then
 * to the cached index.html. Never crashes the page on a fetch failure. */
"use strict";

// KIT_VERSION is the sha256 of the sorted "path + file sha256" list for the whole
// site (excluding this generated file). Rebuilding unchanged content reproduces it,
// so the cache name is stable across builds and rotates only when content changes.
var KIT_VERSION = ${JSON.stringify(version)};
var CACHE = "astro-lab-playground-" + KIT_VERSION;
var INDEX = "/index.html";

// Every path the site needs offline, root-relative to this worker's scope.
var PRECACHE = [
${body}
];

self.addEventListener("install", function (event) {
  event.waitUntil((async function () {
    var cache = await caches.open(CACHE);
    await Promise.all(PRECACHE.map(function (u) {
      // cache.add rejects for any one missing path; swallow per-path so one 404
      // can never abort the whole install.
      return cache.add(new Request(u, { cache: "reload" })).catch(function () {});
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", function (event) {
  event.waitUntil((async function () {
    var keys = await caches.keys();
    await Promise.all(keys.map(function (k) {
      return k === CACHE ? undefined : caches.delete(k);
    }));
    await self.clients.claim();
  })());
});

// Candidate cache keys for a request path: exact, directory index, then root index.
function candidatesFor(pathname) {
  var p = pathname;
  try { p = decodeURIComponent(pathname); } catch (e) {}
  var list = [p];
  if (p === "/") list.push(INDEX);
  else if (p.charAt(p.length - 1) === "/") list.push(p + "index.html");
  return list;
}

async function handle(request) {
  var url;
  try { url = new URL(request.url); } catch (e) { return fetch(request); }
  if (url.origin !== self.location.origin) {
    // Off-site credit links etc.: network only, never cached, never crashes.
    return fetch(request);
  }
  var cache = await caches.open(CACHE);
  var isNav = request.mode === "navigate" || request.destination === "document";
  var cands = candidatesFor(url.pathname);
  for (var i = 0; i < cands.length; i++) {
    try {
      var hit = await cache.match(cands[i]);
      if (hit) return hit;
    } catch (e) {}
  }
  try {
    return await fetch(request);
  } catch (err) {
    if (isNav) {
      try {
        var fallback = await cache.match(INDEX);
        if (fallback) return fallback;
      } catch (e2) {}
    }
    // Signal failure without throwing an uncaught error in the worker.
    return Response.error();
  }
}

self.addEventListener("fetch", function (event) {
  if (event.request.method !== "GET") return;
  event.respondWith(handle(event.request));
});
`;
}

// ---------- zip (STORE method, no timestamps) ----------
const DOS_TIME = 0x0000;          // 00:00:00
const DOS_DATE = 0x0021;          // 1980-01-01, fixed so rebuilds are byte-identical
const SIG_LOCAL = 0x04034b50;
const SIG_CENTRAL = 0x02014b50;
const SIG_EOCD = 0x06054b50;

// entries: [{ name (posix, site-relative), data (Buffer) }], caller supplies in
// sorted order. buildZip does not re-sort; buildSite does, for determinism.
function buildZip(entries) {
  const localChunks = [];
  const centralChunks = [];
  let offset = 0;
  for (const en of entries) {
    const nameBuf = Buffer.from(en.name, "utf8");
    const data = en.data;
    const crc = crc32(data);
    const size = data.length;

    const local = Buffer.alloc(30);
    local.writeUInt32LE(SIG_LOCAL, 0);
    local.writeUInt16LE(20, 4);        // version needed to extract
    local.writeUInt16LE(0, 6);         // general purpose flags (ASCII names)
    local.writeUInt16LE(0, 8);         // method 0 = store
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(size, 18);     // compressed size (store => == uncompressed)
    local.writeUInt32LE(size, 22);     // uncompressed size
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);        // extra field length
    localChunks.push(local, nameBuf, data);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(SIG_CENTRAL, 0);
    central.writeUInt16LE(20, 4);      // version made by
    central.writeUInt16LE(20, 6);      // version needed to extract
    central.writeUInt16LE(0, 8);       // flags
    central.writeUInt16LE(0, 10);      // method = store
    central.writeUInt16LE(DOS_TIME, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(size, 20);
    central.writeUInt32LE(size, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt16LE(0, 30);      // extra length
    central.writeUInt16LE(0, 32);      // comment length
    central.writeUInt16LE(0, 34);      // disk number start
    central.writeUInt16LE(0, 36);      // internal attributes
    central.writeUInt32LE(0, 38);      // external attributes
    central.writeUInt32LE(offset, 42); // relative offset of local header
    centralChunks.push(central, nameBuf);

    offset += 30 + nameBuf.length + size;
  }

  const localBuf = Buffer.concat(localChunks);
  const centralBuf = Buffer.concat(centralChunks);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(SIG_EOCD, 0);
  eocd.writeUInt16LE(0, 4);                       // this disk
  eocd.writeUInt16LE(0, 6);                       // disk with central dir
  eocd.writeUInt16LE(entries.length, 8);          // entries on this disk
  eocd.writeUInt16LE(entries.length, 10);         // total entries
  eocd.writeUInt32LE(centralBuf.length, 12);      // size of central dir
  eocd.writeUInt32LE(localBuf.length, 16);        // offset of central dir
  eocd.writeUInt16LE(0, 20);                      // comment length

  return Buffer.concat([localBuf, centralBuf, eocd]);
}

// ---------- zip reader (stdlib) ----------
// Parses the central directory and, when asked, re-reads each entry's stored bytes
// from its local header so callers can verify integrity.
function readZipEntries(buf, opts) {
  opts = opts || {};
  const wantData = opts.withData !== false;
  let eocd = -1;
  const minPos = Math.max(0, buf.length - (22 + 0xffff));
  for (let i = buf.length - 22; i >= minPos; i--) {
    if (buf.readUInt32LE(i) === SIG_EOCD) { eocd = i; break; }
  }
  if (eocd < 0) throw new Error("not a zip: EOCD not found");
  const count = buf.readUInt16LE(eocd + 10);
  const cdSize = buf.readUInt32LE(eocd + 12);
  const cdOffset = buf.readUInt32LE(eocd + 16);
  const entries = [];
  let p = cdOffset;
  for (let i = 0; i < count; i++) {
    if (buf.readUInt32LE(p) !== SIG_CENTRAL) throw new Error("bad central header at " + p);
    const method = buf.readUInt16LE(p + 10);
    const crc = buf.readUInt32LE(p + 16);
    const compSize = buf.readUInt32LE(p + 20);
    const uncompSize = buf.readUInt32LE(p + 24);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    const localOffset = buf.readUInt32LE(p + 42);
    const name = buf.toString("utf8", p + 46, p + 46 + nameLen);
    const entry = { name, method, crc, compSize, uncompSize };
    if (wantData) {
      if (buf.readUInt32LE(localOffset) !== SIG_LOCAL) throw new Error("bad local header for " + name);
      const lfnLen = buf.readUInt16LE(localOffset + 26);
      const lexLen = buf.readUInt16LE(localOffset + 28);
      const dataStart = localOffset + 30 + lfnLen + lexLen;
      entry.data = buf.slice(dataStart, dataStart + compSize);
      if (method === 0 && crc32(entry.data) !== crc) throw new Error("crc mismatch for " + name);
    }
    entries.push(entry);
    p += 46 + nameLen + extraLen + commentLen;
  }
  return { count, cdOffset, cdSize, entries };
}

// ---------- pure build (used by the writer and the determinism test) ----------
// Reads existing site content, returns the sw source + zip buffer + manifest without
// touching the filesystem. sw.js content is generated fresh and fed straight into the
// zip, so the output is a pure function of the non-generated site content.
function buildSite(siteDir) {
  siteDir = siteDir || SITE_DIR;
  const all = listSiteFiles(siteDir);
  const version = kitVersion(siteDir, all);
  const precache = precacheManifest(all);
  const swSource = buildSw(version, precache);

  const zipNames = precacheManifest(all); // posix + leading slash; strip back
  const entries = zipNames.map((rootRel) => {
    const rel = rootRel.slice(1);
    const data = rel === SW_REL ? Buffer.from(swSource, "utf8") : fs.readFileSync(path.join(siteDir, rel));
    return { name: rel, data };
  });
  const zipBuffer = buildZip(entries);
  return {
    version,
    precache,
    swSource,
    zipBuffer,
    fileCount: entries.length,
    zipBytes: zipBuffer.length,
  };
}

// ---------- writer (only when run directly) ----------
function main() {
  const built = buildSite(SITE_DIR);
  const swPath = path.join(SITE_DIR, SW_REL);
  const zipPath = path.join(SITE_DIR, ZIP_REL);
  fs.mkdirSync(path.dirname(zipPath), { recursive: true });
  fs.writeFileSync(swPath, built.swSource, "utf8");
  fs.writeFileSync(zipPath, built.zipBuffer);
  console.error("KIT_VERSION " + built.version);
  console.error("sw scope: / (site root); cache = astro-lab-playground-" + built.version);
  console.log("files: " + built.fileCount + "  kit.zip bytes: " + built.zipBytes);
}

